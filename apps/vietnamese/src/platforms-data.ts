import { z } from "zod";

const PROJECT_RELEASES = "https://github.com/metasequoiaime/";

/**
 * 地址必须落在本项目的 GitHub 组织下。`z.string().url()` 只判断 `new URL()` 解不解析得了，`javascript:` 和 `data:` 都算合法，而这些地址会直接变成下载按钮的 href。
 *
 * 有一个地址不合规就整份作废：清单由官网的自动化任务生成，出现组织外的地址意味着链路本身出了问题，此时页面回落到发布页链接，比展示一份被悄悄过滤过的清单安全。
 */
const projectUrl = z
  .string()
  .url()
  .refine((value) => value.startsWith(PROJECT_RELEASES), { message: "URL must point at the project's GitHub organisation" });

const downloadSchema = z.object({
  label: z.string(),
  arch: z.string().regex(/^[A-Za-z0-9_+-]{1,24}$/),
  name: z.string(),
  url: projectUrl,
  // The same file on the dl.msime.app mirror. Only an alternative to GitHub: a malformed address drops this one field, not the manifest.
  mirrorUrl: z.url({ protocol: /^https$/, hostname: z.regexes.domain }).optional().catch(undefined),
  size: z.number().int().nonnegative(),
  sha256: z.string().regex(/^[0-9a-f]{64}$/).nullable().catch(null),
});

const releaseSchema = z.object({
  version: z.string().regex(/^\d+(?:\.\d+)*(?:-[0-9A-Za-z.]+)?$/),
  releaseUrl: projectUrl,
  publishedAt: z.string(),
  // true signed, false unsigned, null unknown.
  signed: z.boolean().nullable().catch(null),
  downloads: z.array(downloadSchema).min(1),
});

const platformReleaseSchema = releaseSchema.extend({
  // The msime repository's Windows build, published next to the MSIME-Windows stable line; only Windows has it.
  experimental: releaseSchema.nullable().catch(null),
});

/**
 * The subset of the official site's `platforms.json` (generated by apps/web/scripts/generate-platforms.mjs, copied here by scripts/sync-release-data.mjs) that this site reads. Unknown keys such as the download statistics are dropped.
 */
export const platformsSchema = z.object({
  generatedAt: z.string(),
  platforms: z.object({
    windows: platformReleaseSchema.optional(),
    macos: platformReleaseSchema.optional(),
    linux: platformReleaseSchema.optional(),
    android: platformReleaseSchema.optional(),
  }),
});

export type PlatformsManifest = z.infer<typeof platformsSchema>;
export type Release = z.infer<typeof releaseSchema>;
export type DownloadFile = z.infer<typeof downloadSchema>;
