import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Run once when importing artwork: node scripts/generate-gallery.mjs <source-directory>
// Requires cwebp (WebP tools). Upload output/gallery to R2 before publishing.
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/generate-gallery.mjs <source-directory>");
const project = fileURLToPath(new URL("../", import.meta.url));
const categories = { poses: "姿势", expressions: "表情", outfits: "服装", scenes: "场景" };
const items = [];
const artifacts = [];
for (const [category, folder] of Object.entries(categories)) {
  const output = join(project, "output/gallery/illustrations", category);
  mkdirSync(output, { recursive: true });
  const files = readdirSync(join(source, folder)).filter(file => file.endsWith(".png")).sort((a, b) => a.localeCompare(b, "zh-CN", { numeric: true }));
  for (const file of files) {
    const stem = basename(file, ".png");
    const name = stem.replace(/^\d+-/, "");
    const path = `${category}/${stem}`;
    for (const [width, quality] of [[480, 82], [1536, 88]]) {
      execFileSync("cwebp", ["-quiet", "-mt", "-q", String(quality), "-resize", String(width), "0", resolve(source, folder, file), "-o", join(output, `${stem}-${width}w.webp`)], { stdio: "inherit" });
      const bytes = readFileSync(join(output, `${stem}-${width}w.webp`));
      artifacts.push({ path: `${path}-${width}w.webp`, sha256: createHash("sha256").update(bytes).digest("hex"), size: bytes.length });
    }
    items.push({ category, name, path });
  }
}
mkdirSync(join(project, "src/gallery"), { recursive: true });
const revisionHash = createHash("sha256");
artifacts.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
for (const artifact of artifacts) revisionHash.update(`${artifact.path}\0${artifact.sha256}\n`);
const revision = revisionHash.digest("hex").slice(0, 16);
const baseUrl = `https://media.msime.app/gallery/${revision}/illustrations`;
writeFileSync(join(project, "output/gallery/manifest.json"), `${JSON.stringify({ baseUrl, files: artifacts }, null, 2)}\n`);
writeFileSync(join(project, "src/gallery/items.ts"), `// Generated by scripts/generate-gallery.mjs.\nexport const galleryImageBaseUrl = ${JSON.stringify(baseUrl)};\nexport const galleryItems = ${JSON.stringify(items, null, 2)} as const;\n`);
console.log(`Imported ${items.length} illustrations. Upload output/gallery/illustrations to R2 msime/gallery/${revision}/illustrations before publishing.`);
