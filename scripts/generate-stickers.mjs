import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

// Run when the sticker set changes: node scripts/generate-stickers.mjs <sticker-directory>
// The directory holds telegram/ and discord/ PNG folders plus README.md (usage terms). Upload output/stickers to R2 before publishing.
const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/generate-stickers.mjs <sticker-directory>");
const project = fileURLToPath(new URL("../", import.meta.url));
const output = join(project, "output/stickers");
rmSync(output, { recursive: true, force: true });
mkdirSync(output, { recursive: true });
const packs = [
  { id: "telegram", label: "Telegram", spec: "PNG · 长边 512px · 透明底" },
  { id: "discord", label: "Discord", spec: "PNG · 320×320 · 单张小于 512KB" },
];
const results = [];
for (const pack of packs) {
  const files = readdirSync(join(source, pack.id)).filter(file => file.endsWith(".png")).sort((a, b) => a.localeCompare(b, "zh-CN", { numeric: true }));
  const folder = `shuishan-niang-stickers-${pack.id}`;
  const staging = join(output, "staging", folder);
  mkdirSync(staging, { recursive: true });
  for (const file of files) cpSync(join(source, pack.id, file), join(staging, file));
  cpSync(join(source, "README.md"), join(staging, "README.md"));
  // Python's zipfile marks non-ASCII names as UTF-8 (general purpose flag bit 11); Info-ZIP's zip does not, and Windows Explorer then shows the Chinese file names garbled.
  execFileSync("python3", ["-I", "-m", "zipfile", "-c", join(output, `${folder}.zip`), folder], { cwd: join(output, "staging") });
  const bytes = readFileSync(join(output, `${folder}.zip`));
  results.push({ ...pack, file: `${folder}.zip`, count: files.length, size: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") });
}
rmSync(join(output, "staging"), { recursive: true, force: true });
const revision = createHash("sha256").update(results.map(pack => `${pack.file}\0${pack.sha256}\n`).join("")).digest("hex").slice(0, 16);
const baseUrl = `https://media.msime.app/gallery/stickers/${revision}`;
writeFileSync(join(output, "manifest.json"), `${JSON.stringify({ baseUrl, files: results.map(({ file, size, sha256 }) => ({ path: file, size, sha256 })) }, null, 2)}\n`);
writeFileSync(join(project, "src/gallery/stickers.ts"), `// Generated by scripts/generate-stickers.mjs.\nexport const stickerBaseUrl = ${JSON.stringify(baseUrl)};\nexport const stickerPacks = ${JSON.stringify(results.map(({ id, label, spec, file, count, size }) => ({ id, label, spec, file, count, size })), null, 2)} as const;\n`);
console.log(`Packed ${results.map(pack => `${pack.count} ${pack.label}`).join(", ")} stickers. Upload output/stickers/*.zip to R2 msime/gallery/stickers/${revision}/ before publishing.`);
